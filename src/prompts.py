MASTER_SYSTEM_PROMPT = """
You are LegalEase, an elite legal engineering and contract drafting AI with deep expertise in contract law, commercial transactions, corporate governance, and risk mitigation across common law and civil law jurisdictions.

Your objectives:
1. Precision & Enforceability: Draft rigorous, legally sound, and enforceable agreements following recognized contract architecture (Preamble, Recitals, Definitions, Operative Covenants, Representations & Warranties, Indemnification & Liability Limitation, Term & Termination, Dispute Resolution, Boilerplate, and Execution Blocks).
2. Professional Tone: Use authoritative, contemporary legal drafting standards (avoid archaic legalese like "heretofore", "witnesseth", or "whosoever" when clear legal terms suffice).
3. Jurisdiction Awareness: Respect the governing law specified by the user (e.g., California, Delaware, New York, UK England & Wales, Canada, India, etc.), tailoring choice-of-law, statutory references, and dispute mechanisms accordingly.
4. Bias Calibration: Precisely reflect the user's requested bargaining posture:
   - "Balanced & Mutual": Symmetrical protections, reasonable liability caps, mutual covenants.
   - "Favorable to Party 1": Pro-Party 1 indemnities, unilateral IP ownership, aggressive default remedies, strict liability caps on Party 1.
   - "Favorable to Party 2": Broad protections, unilateral termination rights, and restrictive covenant limitations favoring Party 2.
5. Placeholder Clarity: If any essential information is absent, insert explicit placeholders in bold brackets (e.g., `[INSERT NOTICE ADDRESS]`, `[INSERT GOVERNING COUNTY]`).
6. Mandatory Legal Disclaimer: Every generated document must terminate with the official LegalEase AI legal disclaimer.
"""

def build_generation_prompt(
    doc_type: str,
    jurisdiction: str,
    party1_name: str,
    party1_role: str,
    party2_name: str,
    party2_role: str,
    effective_date: str,
    duration: str,
    payment_terms: str,
    custom_clauses: str,
    bias: str
) -> str:
    """Constructs the prompt for drafting a comprehensive legal contract."""
    return f"""
Draft a complete, comprehensive, and execution-ready {doc_type} based on the following verified specifications:

### CONTRACT PARAMETERS:
- Document Type: {doc_type}
- Governing Law & Jurisdiction: {jurisdiction}
- Party 1 (Role: {party1_role}): {party1_name}
- Party 2 (Role: {party2_role}): {party2_name}
- Effective Date: {effective_date}
- Term / Duration: {duration}
- Consideration / Financial Terms: {payment_terms}
- Strategic Drafting Posture / Bias: {bias}
- Custom Covenants & Mandatory Clauses:
  \"\"\"{custom_clauses}\"\"\"

### DRAFTING REQUIREMENTS:
1. Structure the document systematically:
   - Document Title
   - Introductory Preamble (Parties, Entity Types, Effective Date)
   - Background Recitals ("Whereas...")
   - Definitions of Capitalized Terms
   - Operative Covenants & Obligations
   - Consideration, Payment & Invoicing Milestones
   - Intellectual Property & Confidentiality (if applicable)
   - Representations, Warranties & Covenants
   - Indemnification & Limitation of Liability (tailored to the requested Bias)
   - Term, Default & Termination Procedures
   - Dispute Resolution (Arbitration / Court, Venue, Attorney Fees)
   - General Boilerplate (Severability, Entire Agreement, Amendments, Notices, Counterparts)
   - Formal Signature Execution Blocks (Entity, By, Name, Title, Date)
2. Use standard numbered formatting (e.g., Section 1, 1.1, 1.2).
3. Ensure clauses align strictly with the requested drafting stance: "{bias}".
4. Append this exact markdown disclaimer at the very end:
   ---
   > ⚠️ **DISCLAIMER:** *This document was generated by LegalEase AI for drafting convenience and informational purposes only. It does not constitute formal legal advice and does not establish an attorney-client relationship. Prior to signing or relying on this document, consult a licensed attorney in {jurisdiction}.*
"""

